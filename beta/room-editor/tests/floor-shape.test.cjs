'use strict';
const assert=require('node:assert/strict'),shape=require('../shape.js'),portals=require('../portals.js');
const room={width:3,height:3,walls:[],furniture:[],portals:[{side:'south',offset:1,width:1}]};
const bounds=o=>o.bounds;
const cut=shape.edit(room,2,2,false,bounds).room;
assert.equal(shape.has(cut,2,2),false);
assert.equal(shape.cells(cut).length,8);
assert.equal(shape.contains(cut,{left:1.9,right:2.1,top:1.9,bottom:2.1}),false);
const notch=portals.nearest(cut,2.5,2.01);
assert.deepEqual(notch,{side:'south',line:2,offset:2,width:1});
assert.equal(portals.inspect(cut,notch,{walls:{},furniture:{}},{bounds}).ok,true);
const expanded=shape.edit(cut,-1,1,true,bounds);
assert.equal(expanded.dx,1);assert.equal(expanded.room.width,4);
assert.deepEqual(expanded.room.portals[0],{side:'south',offset:2,width:1,line:3});
assert.equal(shape.edit(cut,8,8,true,bounds).ok,false);
const thin={width:3,height:2,floorCells:[{x:0,y:0},{x:1,y:0},{x:2,y:0}],walls:[],furniture:[]};
assert.equal(shape.edit(thin,1,0,false,bounds).ok,false);
assert.equal(shape.edit({...thin,furniture:[{x:0.5,y:0.5,bounds:{left:0,right:1,top:0,bottom:1}}]},0,0,false,bounds).ok,false);
console.log('Floor mask, connectivity, void collision, concave portal and expansion OK');
